#!/usr/bin/env python3
"""Stamp cache-busting versions after editing Vedic Math.

    python3 build.py

This repo is served at https://sbmadhav.com/vedic-math/ (GitHub project Pages under the
sbmadhav.github.io custom domain), so every page URL starts with /vedic-math/.

- index.html gets an import map that pins every module under /vedic-math/js/ (skills/
  included) to ?v=<hash of that file>, so a visitor never runs a new app.js against old
  imports. The entry script and math.css are stamped the same way. The map sits between
  the "site-build: import map" markers and is rewritten on every run.
- Files that live in the main site repo (sbmadhav.github.io) are loaded by absolute URL
  with no ?v= stamp, because this repo cannot hash them: the design-system CSS, the
  Explore menu, analytics, fonts and icons. That is the same pattern as
  /state-of-voice-agents/.
- sw.js (the offline service worker, scope /vedic-math/) gets its precache list and VERSION
  between the "build.py: precache" markers: every file of this repo the page loads, at the exact
  URL index.html uses, with a hash the worker checks on install, plus the shared files index.html
  and manifest.webmanifest reference (no hash: this repo cannot see them). VERSION hashes all of
  that and the rest of sw.js, so any change to the app means a new cache.

Running it twice changes nothing the second time.
"""
import hashlib, json, pathlib, posixpath, re

root = pathlib.Path(__file__).resolve().parent
BASE = "/vedic-math/"
h = lambda b: hashlib.sha256(b).hexdigest()[:10]
fhash = lambda p: h((root / p).read_bytes())

def write(path, text):
    f = root / path
    if f.read_text() != text:
        f.write_text(text)

js = sorted(p.relative_to(root).as_posix() for p in (root / "js").rglob("*.js"))
versions = {BASE + p: fhash(p) for p in js}

# Every static import must be a relative or absolute path inside /vedic-math/js/, or a full URL
# (CDN). A bare specifier would fail without the map, and a path outside the folder would not be pinned.
import_re = re.compile(r"""(?:^|[;\n}])\s*(?:import|export)\b[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]|(?:^|[;\n}])\s*import\s*['"]([^'"]+)['"]""")
for p in js:
    src = (root / p).read_text()
    for m in import_re.finditer(src):
        spec = m.group(1) or m.group(2)
        if re.match(r"https?://", spec):
            continue
        if not spec.startswith(("./", "../", "/")):
            raise SystemExit(f"{p}: bare import '{spec}' is not covered by the import map")
        resolved = posixpath.normpath(spec if spec.startswith("/") else posixpath.join(posixpath.dirname(BASE + p), spec))
        if resolved not in versions:
            raise SystemExit(f"{p}: import '{spec}' resolves to {resolved}, outside the versioned /vedic-math/js/ modules")

imports = {u: f"{u}?v={v}" for u, v in versions.items()}
MAP_START, MAP_END = "<!-- site-build: import map (generated by build.py, do not edit) -->", "<!-- /site-build: import map -->"
map_block = MAP_START + '\n<script type="importmap">\n' + json.dumps({"imports": imports}, indent=1) + "\n</script>\n" + MAP_END + "\n"

html = (root / "index.html").read_text()
html = re.sub(r"<!-- site-build: import map[^>]*-->.*?" + re.escape(MAP_END) + r"\n?", "", html, flags=re.S)
entry = re.search(r'<script type="module" src="/vedic-math/js/app\.js(?:\?v=[\w_]+)?"></script>', html)
if not entry:
    raise SystemExit("index.html: module entry script not found")
html = html[:entry.start()] + map_block + html[entry.start():]
assert html.count('type="importmap"') == 1

own = {BASE + "js/app.js": versions[BASE + "js/app.js"], BASE + "math.css": fhash("math.css")}
for url, v in own.items():
    html, n = re.subn(r'((?:src|href)=")' + re.escape(url) + r'(?:\?v=[\w_]+)?"', rf'\g<1>{url}?v={v}"', html)
    if not n:
        raise SystemExit(f"index.html: no reference to {url}")

# Shared files from the main site: absolute URL, no stamp (this repo cannot see their contents)
SHARED = ["/design-system/tokens.css", "/design-system/components.css", "/assets/explore.js", "/assets/analytics.js"]
for url in SHARED:
    html, n = re.subn(r'((?:src|href)=")' + re.escape(url) + r'(?:\?v=[\w_]+)?"', rf'\g<1>{url}"', html)
    if not n:
        raise SystemExit(f"index.html: no reference to {url}")

write("index.html", html)

# Offline: the service worker's precache list. Files of this repo are listed at the URL the page uses,
# with a hash the worker checks on install; shared files from the main site are listed without one.
own_files = {BASE: "index.html", f"{BASE}math.css?v={own[BASE + 'math.css']}": "math.css", BASE + "manifest.webmanifest": "manifest.webmanifest"}
own_files.update({imports[BASE + p]: p for p in js})
refs = set(re.findall(r'(?:src|href)="(/[^"]*)"', html)) | set(re.findall(r'url\((/[^)]+)\)', html))
manifest = json.loads((root / "manifest.webmanifest").read_text())
refs |= {posixpath.join(BASE, i["src"]) for i in manifest.get("icons", [])}
shared = sorted(u for u in refs if u != "/" and not u.startswith(BASE))
missing = sorted(u for u in refs if u.startswith(BASE) and u not in own_files)
if missing:
    raise SystemExit(f"index.html: {', '.join(missing)} would not be saved for offline use; add it to own_files in build.py")
precache = [[u, fhash(f)] for u, f in own_files.items()] + [[u, None] for u in shared]

SW_START, SW_END = "/* build.py: precache (generated, do not edit) */", "/* /build.py: precache */"
sw = (root / "sw.js").read_text()
block = re.compile(re.escape(SW_START) + r".*?" + re.escape(SW_END), re.S)
if len(block.findall(sw)) != 1:
    raise SystemExit("sw.js: precache markers not found")
listing = "[\n" + ",\n".join(" " + json.dumps(e) for e in precache) + "\n]"
sw_version = h((listing + block.sub(SW_START + SW_END, sw)).encode())
sw = block.sub(lambda m: f"{SW_START}\nconst VERSION = '{sw_version}';\nconst PRECACHE = {listing};\n{SW_END}", sw)
write("sw.js", sw)

print(f"{len(imports)} Vedic Math modules pinned, app.js v={own[BASE + 'js/app.js']}, math.css v={own[BASE + 'math.css']}, "
      f"sw.js v={sw_version} ({len(own_files)} own + {len(shared)} shared files precached)")
