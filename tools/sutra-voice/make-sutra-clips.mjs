/* sutra-pronunciation: makes the name clip of every Sutra and sub-sutra, locally and for free (repo-only tool).
   kokoro-js runs the open Kokoro-82M model (Apache-2.0) on this machine. kokoro-js only exposes its English front
   end, so the phonemes come from sanskrit.mjs (the IAST read letter by letter, every short a said) and go straight
   to the model with a Kokoro Hindi voice. The voice is the one the owner chose on the listening page
   (docs/prototypes/sutra-voice/, design.md owner decision 1): the Alpha kid blend, a weighted average of the style
   vectors of Kokoro's Hindi voice Alpha (70%) and its lighter Japanese voice Alpha (30%). No pitch shifting.
   Format: AAC in .m4a, mono, 24 kHz, 32 kbps (macOS afconvert), the same as the better-voice change.
   Run:  cd tools/sutra-voice && npm install && node make-sutra-clips.mjs [s1,u7]
   Writes ../../sounds/sutras/<id>.m4a and the generated index ../../js/say-clips.js (bytes and a content hash
   per clip; the hash is the clip URL's ?v= so a remade clip is fetched again). With ids, remakes only those. */
import { readFileSync, writeFileSync, mkdirSync, rmSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { NAMES, appId } from './names.mjs';
import { toIPA } from './sanskrit.mjs';

const ROOT = new URL('../../', import.meta.url).pathname;
const DIR = ROOT + 'sounds/sutras/', INDEX = ROOT + 'js/say-clips.js';
const VOICES = new URL('./node_modules/kokoro-js/voices/', import.meta.url).pathname;
const RATE = 24000, BITRATE = 32000, SPEED = 0.85;
export const VOICE = { id: 'kid_alpha_jalpha', mix: { hf_alpha: 0.7, jf_alpha: 0.3 }, label: 'Alpha kid blend: Kokoro Hindi Alpha 70%, Japanese Alpha 30%' };

/* The index the app imports. Kept here so the test can rebuild it from the files and compare. */
export const hashOf = buf => createHash('sha256').update(buf).digest('hex').slice(0, 10);
export function indexSource(rows) {
  return `/* Generated by tools/sutra-voice/make-sutra-clips.mjs: do not edit. One name clip per Sutra and sub-sutra
   (sounds/sutras/<id>.m4a), voice ${VOICE.label}, AAC mono ${RATE / 1000} kHz ${BITRATE / 1000} kbps.
   bytes: the file size; v: the first 10 hex of its SHA-256, used as the clip URL's ?v= (test/say.test.mjs checks both). */
export const VOICE = '${VOICE.id}';
export const CLIPS = {
${rows.map(r => `  ${r.id}: { bytes: ${r.bytes}, v: '${r.v}' }`).join(',\n')}
};
`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const { KokoroTTS } = await import('kokoro-js');
  const { Tensor } = await import('@huggingface/transformers');
  const voiceData = name => { const b = readFileSync(VOICES + name + '.bin'); return new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
  const mixData = Object.entries(VOICE.mix).map(([n, w]) => [voiceData(n), w]);
  /* What generate_from_ids does, with the blended style vector: the style row is picked by input length */
  async function synth(tts, ids) {
    const row = 256 * Math.min(Math.max(ids.dims.at(-1) - 2, 0), 509), style = new Float32Array(256);
    for (const [v, w] of mixData) for (let i = 0; i < 256; i++) style[i] += w * v[row + i];
    const { waveform } = await tts.model({ input_ids: ids, style: new Tensor('float32', style, [1, 256]), speed: new Tensor('float32', [SPEED], [1]) });
    return new Float32Array(waveform.data);
  }
  const trim = (a, thr = 0.012, pad = Math.round(RATE * 0.04)) => {
    let s = 0, e = a.length - 1;
    while (s < a.length && Math.abs(a[s]) < thr) s++;
    while (e > s && Math.abs(a[e]) < thr) e--;
    return a.slice(Math.max(0, s - pad), Math.min(a.length, e + pad + 1));
  };
  const fade = a => { const n = Math.min(a.length, Math.round(RATE * 0.015)); for (let i = 0; i < n; i++) { a[i] *= i / n; a[a.length - 1 - i] *= i / n; } return a; };
  const wav = (f32, path) => {
    const n = f32.length, buf = Buffer.alloc(44 + n * 2);
    buf.write('RIFF', 0); buf.writeUInt32LE(36 + n * 2, 4); buf.write('WAVEfmt ', 8); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
    buf.writeUInt32LE(RATE, 24); buf.writeUInt32LE(RATE * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34); buf.write('data', 36); buf.writeUInt32LE(n * 2, 40);
    for (let i = 0; i < n; i++) buf.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(f32[i] * 32767))), 44 + i * 2);
    writeFileSync(path, buf);
  };
  const m4a = (f32, path) => { const tmp = path.replace(/\.m4a$/, '.wav'); wav(f32, tmp); execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', String(BITRATE), '-c', '1', tmp, path]); rmSync(tmp); };

  const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', { dtype: 'fp32', device: 'cpu' });
  const vocab = tts.tokenizer.model.tokens_to_ids;
  const known = s => [...s].filter(ch => ch === ' ' || vocab.has(ch)).join('');
  if (known('ʃuːnjəm') !== 'ʃuːnjəm') throw new Error('Kokoro vocabulary lookup is broken');

  const only = process.argv[2] ? new Set(process.argv[2].split(',')) : null;
  mkdirSync(DIR, { recursive: true });
  const rows = [];
  for (const name of NAMES) {
    const id = appId(name.id), file = DIR + id + '.m4a';
    if (!only || only.has(id) || !existsSync(file)) {
      const { input_ids } = tts.tokenizer(known(toIPA(name.say)), { truncation: true });
      m4a(fade(trim(await synth(tts, input_ids))), file);
      console.log(id, name.iast, statSync(file).size, 'bytes');
    }
    const buf = readFileSync(file);
    rows.push({ id, bytes: buf.length, v: hashOf(buf) });
  }
  writeFileSync(INDEX, indexSource(rows));
  console.log(`${rows.length} clips, ${Math.round(rows.reduce((a, r) => a + r.bytes, 0) / 1024)} KB in all; wrote js/say-clips.js`);
}
