/* Writes js/voice-index.js, the small module the app reads to find the studio voice's files (record.mjs, publish.mjs) */
import { writeFileSync } from 'node:fs';
export const INDEX_PATH = new URL('../../js/voice-index.js', import.meta.url).pathname;
export function indexModule(idx) {
  return `/* Studio voice index: GENERATED by tools/voice/record.mjs and tools/voice/publish.mjs. Do not edit by hand.
   The recordings are not in git: publish.mjs uploads them as one archive to the GitHub Release named by tag, and the
   CI deploy unpacks it into /vedic-math/voice/ after checking sha256 (tools/voice/ci-fetch.mjs). With no tag, nothing
   has been recorded yet and read aloud uses the built-in voice. */
export const STUDIO = ${JSON.stringify(idx, null, 2)};
`;
}
export const writeIndex = idx => writeFileSync(INDEX_PATH, indexModule(idx));
